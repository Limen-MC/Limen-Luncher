const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('fs')
const path = require('path')
const os = require('os')
const AdmZip = require('adm-zip')
const { prepareRuntime, mergeProfile, inside } = require('../app/assets/js/limen-runtime')
const root = path.join(__dirname, '../app/runtime')
const profile = JSON.parse(fs.readFileSync(path.join(root, 'fabric-profile.json')))
function vanilla() { return { id: '26.3', mainClass: 'net.minecraft.client.main.Main', arguments: { jvm: ['-cp', '${classpath}'], game: ['--username', '${auth_player_name}'] }, libraries: [{ name: 'unrelated:library:1', downloads: { artifact: { path: 'unrelated.jar' } } }] } }
test('Profil Fabric fusionné sans altérer le manifeste Mojang ni son client.jar', () => {
    const source = vanilla()
    const copy = JSON.stringify(source)
    const result = mergeProfile(source, profile)
    assert.equal(result.id, '26.3')
    assert.equal(result.mainClass, 'net.fabricmc.loader.impl.launch.knot.KnotClient')
    assert(result.limenFabric)
    assert(result.libraries.some(lib => lib.name.startsWith('net.fabricmc:fabric-loader:')))
    assert.equal(JSON.stringify(source), copy)
    assert.throws(() => mergeProfile({ ...source, id: '1.21' }, profile), /incompatible/)
})
test('Installation idempotente, sauvegarde des anciens mods gérés et conservation des autres', () => {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'limen-runtime-'))
    try {
        const mods = path.join(tmp, 'instances/limen-main/mods')
        fs.mkdirSync(mods, { recursive: true })
        const old = new AdmZip()
        old.addFile('fabric.mod.json', Buffer.from(JSON.stringify({ id: 'nyven', version: 'old' })))
        old.writeZip(path.join(mods, 'old-nyven.jar'))
        fs.writeFileSync(path.join(mods, 'mon-autre-mod.jar'), 'do not touch')
        prepareRuntime(path.join(tmp, 'common'), path.join(tmp, 'instances'), 'limen-main', vanilla())
        assert(fs.existsSync(path.join(mods, 'Nyven-Limen-1.6.1-mc26.3.jar')))
        assert(!fs.existsSync(path.join(mods, 'old-nyven.jar')))
        const backups = path.join(tmp, 'instances/limen-main/limen-mod-backups')
        assert.equal(fs.readdirSync(backups).length, 1)
        prepareRuntime(path.join(tmp, 'common'), path.join(tmp, 'instances'), 'limen-main', vanilla())
        assert.equal(fs.readdirSync(backups).length, 1)
        assert.equal(fs.readFileSync(path.join(mods, 'mon-autre-mod.jar'), 'utf8'), 'do not touch')
    } finally { fs.rmSync(tmp, { recursive: true, force: true }) }
})
test('Intégrité du pack contrôlée avant toute copie et refus des chemins sortants', () => {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'limen-bad-pack-'))
    try {
        const source = path.join(tmp, 'bundle')
        fs.cpSync(root, source, { recursive: true })
        const manifest = JSON.parse(fs.readFileSync(path.join(source, 'bundle.json')))
        fs.appendFileSync(path.join(source, manifest.mods[0].file), 'corrupt')
        assert.throws(() => prepareRuntime(path.join(tmp, 'common'), path.join(tmp, 'instances'), 'limen-main', vanilla(), source), /endommagé/)
        assert(!fs.existsSync(path.join(tmp, 'instances')))
        assert.throws(() => inside(tmp, '../escape.jar'), /invalide/)
    } finally { fs.rmSync(tmp, { recursive: true, force: true }) }
})
