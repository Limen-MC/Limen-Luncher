const {app,BrowserWindow}=require('electron')
const path=require('path')
app.disableHardwareAcceleration()
app.commandLine.appendSwitch('headless')
app.commandLine.appendSwitch('ozone-platform','headless')
app.whenReady().then(async()=>{
 const win=new BrowserWindow({width:1280,height:820,show:false,webPreferences:{offscreen:true}})
 await win.loadFile(path.join(__dirname,'../app/preview.html'))
 await new Promise(r=>setTimeout(r,1500))
 const image=await win.webContents.capturePage()
 require('fs').writeFileSync(path.join(__dirname,'../../Accueil_1280.png'),image.toPNG())
 console.log('CAPTURE_OK')
 app.quit()
}).catch(e=>{console.error(e);app.exit(1)})
